export function translate(
  locale: Locale,
  text: string,
  values?: Record<string, string | number>,
): string {
  let result = text;
  if (locale === "pt-BR") {
    result = ptBR[text] ?? text;
    // Spring validation errors include a field prefix and sometimes a size range.
    const field = /^(name|email|password|phoneNumber): (.+)$/.exec(text);
    if (field) {
      const labels: Record<string, string> = {
        name: "Nome",
        email: "E-mail",
        password: "Senha",
        phoneNumber: "WhatsApp",
      };
      const size = /^size must be between (\d+) and (\d+)$/.exec(field[2]);
      const message = size
        ? `Use de ${size[1]} a ${size[2]} caracteres.`
        : (ptBR[field[2]] ?? "Confira o valor informado.");
      result = labels[field[1]] + ": " + message;
    }
  }
  return result.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values?.[name] !== undefined ? String(values[name]) : placeholder,
  );
}
